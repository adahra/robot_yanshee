"""Integration tests for dynamic tool creation in yanshee_detect_any.py."""
import os
import json
import unittest
from unittest.mock import patch

import types

# Inject a fake YanAPI before importing the module under test.
_fake_yanapi = types.ModuleType("YanAPI")
_fake_yanapi.yan_api_init = lambda *a, **k: None
_fake_yanapi.sync_do_tts = lambda *a, **k: None
_fake_yanapi.set_robot_led = lambda *a, **k: None
_fake_yanapi.sync_play_motion = lambda *a, **k: True
_fake_yanapi.sync_do_gesture_recognition = lambda: {}
_fake_yanapi.sync_do_face_recognition_value = lambda *a, **k: {}
_fake_yanapi.sync_do_voice_iat_value = lambda *a, **k: ""
_fake_yanapi.stop_play_music = lambda *a, **k: None
_fake_yanapi.stop_play_motion = lambda *a, **k: None
_fake_yanapi.get_media_music_state = lambda *a, **k: {}
import sys
sys.modules["YanAPI"] = _fake_yanapi

import yanshee_detect_any as yda  # noqa: E402


class TestToolIntegration(unittest.TestCase):
    def setUp(self):
        self._orig_tools = [t for t in yda.tools]
        self._orig_executors = dict(yda.tool_executors)
        # Isolate custom_tools.json
        self._test_file = "test_custom_tools_integration.json"
        if os.path.exists("custom_tools.json"):
            os.replace("custom_tools.json", "custom_tools.json.bak")

    def tearDown(self):
        yda.tools[:] = self._orig_tools
        yda.tool_executors.clear()
        yda.tool_executors.update(self._orig_executors)
        for fn in ("custom_tools.json", "custom_tools.json.bak", self._test_file):
            pass
        if os.path.exists("custom_tools.json.bak"):
            os.replace("custom_tools.json.bak", "custom_tools.json")
        if os.path.exists("custom_tools.json"):
            # remove generated by test
            try:
                os.remove("custom_tools.json")
            except OSError:
                pass

    def test_meta_tool_registered(self):
        tool_names = [t["function"]["name"] for t in yda.tools]
        self.assertIn("create_motion_routine", tool_names)
        self.assertIn("create_motion_routine", yda.tool_executors)

    def test_create_motion_routine_executor(self):
        args = {
            "name": "salam_dua_tangan",
            "description": "Melambaikan tangan dua arah lalu reset",
            "steps": [
                {"action": "wave", "direction": "both", "repeat": 1, "delay": 0.1},
                {"action": "reset", "direction": "", "repeat": 1, "delay": 0.0}
            ]
        }
        resp, is_fallback = yda.tool_executors["create_motion_routine"](args)
        self.assertFalse(is_fallback)
        self.assertIn("salam_dua_tangan", resp)
        tool_names = [t["function"]["name"] for t in yda.tools]
        self.assertIn("salam_dua_tangan", tool_names)
        self.assertIn("salam_dua_tangan", yda.tool_executors)

    def test_routine_runner_runs(self):
        steps = [{"action": "wave", "direction": "left", "repeat": 1, "delay": 0.0}]
        runner = yda._create_routine_runner(steps)
        self.assertTrue(callable(runner))
        self.assertTrue(runner())

    def test_load_and_register(self):
        data = {
            "rutin_uji": {
                "name": "rutin_uji",
                "description": "uji",
                "steps": [{"action": "bow", "direction": "", "repeat": 1, "delay": 0.0}]
            }
        }
        with open("custom_tools.json", "w", encoding="utf-8") as f:
            json.dump(data, f)
        yda.load_and_register_custom_routines("custom_tools.json")
        self.assertIn("rutin_uji", [t["function"]["name"] for t in yda.tools])
        os.remove("custom_tools.json")


if __name__ == "__main__":
    unittest.main()
